const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const packagePath = path.join(root, "package.json");
const versionTsPath = path.join(root, "src", "version.ts");
const runNumber = process.argv[2];

if (!/^\d+$/.test(String(runNumber || ""))) {
  throw new Error("A numeric GitHub Actions run number is required.");
}

const pkg = JSON.parse(fs.readFileSync(packagePath, "utf8"));
const match = /^(\d+)\.(\d+)\.(\d+)$/.exec(String(pkg.version || ""));
if (!match) {
  throw new Error("package.json must contain a stable numeric base version (x.y.z).");
}

const major = Number(match[1]);
const minor = Number(match[2]);
const patch = Number(match[3]) + 1;
const version = `${major}.${minor}.${patch}-beta.${runNumber}`;
pkg.version = version;
fs.writeFileSync(packagePath, JSON.stringify(pkg, null, 2) + "\n", "utf8");

const today = new Date().toISOString().slice(0, 10);
const versionTs = `/** Application version generated by the Pre-Production workflow. */
export const APP_VERSION = "${version}";
export const APP_NAME = "BillingOnHand-Beta";
export const APP_DISPLAY_NAME = "Billing On Hand Beta - Pre-Release Testing";
export const APP_BUILD_DATE = "${today}";
export const GITHUB_OWNER = "devrupeshgadkhe";
export const GITHUB_REPO = "Repo_billingOnHands";
export const GITHUB_RELEASES_URL = \`https://github.com/\${GITHUB_OWNER}/\${GITHUB_REPO}/releases\`;
`;
fs.writeFileSync(versionTsPath, versionTs, "utf8");
console.log(`Pre-Production build version: ${version}`);
